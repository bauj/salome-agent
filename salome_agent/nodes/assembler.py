# result.py runs standalone under `salome shell` with no executor process
# attached, so it must self-init the same way the executor's exec namespace
# does (import convention confirmed 2026-08-29 for this SALOME build).

# KERNEL moved salome/SALOMEDS under salome.kernel after 9.16; the fallback
# keeps generated scripts runnable on SALOME <= 9.16.
_KERNEL_INIT = """try:
    from salome.kernel import salome
except ImportError:
    import salome
salome.salome_init()
"""

_GEOM_INIT = """from salome.geom import geomBuilder
geompy = geomBuilder.New()
"""

_SMESH_INIT = """from salome.smesh import smeshBuilder
smesh = smeshBuilder.New()
"""

_SALOMEDS_INIT = """try:
    from salome.kernel import SALOMEDS
except ImportError:
    import SALOMEDS
"""

_GUI_INIT = """gg = salome.ImportComponentGUI("GEOM")
"""

# Only emitted when a stage actually looks an object up in the study by name
# (a cross-stage / cross-module reference — codegen emits `find_object("x")`).
_FIND_OBJECT = """def find_object(name):
    def walk(sobj):
        it = salome.myStudy.NewChildIterator(sobj)
        while it.More():
            child = it.Value()
            if child.GetName() == name:
                return child.GetObject()
            found = walk(child)
            if found is not None:
                return found
            it.Next()
        return None
    result = walk(salome.myStudy.FindObjectID("0:1"))
    if result is None:
        raise LookupError(f"no study object named {name!r}")
    return result
"""


def commit_stages(graph, state: dict):
    turn = state.get("turn_idx") or 0
    if len(graph.requests) <= turn:
        graph.requests.append(state["user_request"])
    total = len(state["stages"])
    for idx in sorted(state["stages"]):
        stage = state["stages"][idx]
        if stage.get("status") != "ok":
            continue
        where = f"stage {idx + 1}/{total}" if turn == 0 else f"turn {turn + 1} stage {idx + 1}/{total}"
        label = f"{where}: {stage['module']}"
        calls = stage.get("calls")
        if calls is not None and _is_tool_module(stage["module"]):
            bid = graph.add_block(turn, label, stage["module"], stage.get("result_names") or [])
            for c in calls:
                graph.append(bid, c["tool"], c["tool_args"], c["records"], turn,
                             module=stage["module"])
        elif stage.get("script"):
            graph.add_block(turn, label, stage["module"], [], script=stage["script"])
    return graph


def _is_tool_module(module: str) -> bool:
    from salome_agent.modules import spec_for
    return bool(spec_for(module).call_prefix)


def _geom_bodies(graph) -> dict:
    from salome_agent.codegen import _reachable, generate, roots_for
    from salome_agent.modules import spec_for

    per_block, roots = {}, []
    for b in graph.blocks:
        if b.script is None:
            records = [r for n in graph.block_nodes(b.id) for r in n.records]
            names = b.result_names or [p for n in graph.block_nodes(b.id) for p in n.published]
            per_block[b.id] = (records, names)
            roots += roots_for(records, names)
    everything = [r for records, _ in per_block.values() for r in records]
    keep = _reachable(everything, roots)
    module = {b.id: b.module for b in graph.blocks}
    out = {}
    for bid, (records, names) in per_block.items():
        spec = spec_for(module[bid])
        out[bid] = generate(records, names, call_prefix=spec.call_prefix or "geompy.",
                            keep=keep, publish_line=spec.publish_line)
    return out


def render_script(graph, run_id: str) -> str:
    from salome_agent.modules import spec_for

    requests = graph.requests or [""]
    def comment(text):
        return "\n".join(f"# {line}".rstrip() for line in text.splitlines() or [""])

    header = f"# generated by salome-agent, run {run_id}\n{comment('request: ' + requests[0])}\n"
    for i, r in enumerate(requests[1:], start=2):
        header += comment(f"turn {i}: {r}") + "\n"

    geom_bodies = _geom_bodies(graph)
    bodies = []
    modules = set()
    for b in graph.blocks:
        text = b.script if b.script is not None else geom_bodies.get(b.id)
        if text:
            bodies.append(f"# {b.label}\n{text}")
            modules.add(b.module)
    body = "\n\n".join(bodies)

    preamble = _KERNEL_INIT
    # geom's init always comes first — matches main's fixed preamble order.
    if "geom" in modules or "geompy" in body:
        preamble += _GEOM_INIT
    # Module-driven preamble from specs (smesh)
    for name in sorted(modules):
        spec = spec_for(name)
        if spec.preamble and spec.preamble not in preamble:
            preamble += spec.preamble
    # Body-sniffing heuristics for backward compatibility
    if "smesh" in body and _SMESH_INIT not in preamble:
        preamble += _SMESH_INIT
    if "SALOMEDS.Color(" in body:
        preamble += _SALOMEDS_INIT
    if "gg." in body:
        preamble += _GUI_INIT
    if "find_object(" in body:
        preamble += _FIND_OBJECT
    if "study_ns" in body:
        preamble += 'study_ns = "salome_agent_run"\n'

    postamble = "".join(spec_for(name).postamble for name in sorted(modules))
    return header + "\n" + preamble + "\n" + body + "\n" + postamble


def assemble(state: dict) -> str:
    from salome_agent.build_graph import BuildGraph

    graph = commit_stages(BuildGraph.from_dict(state.get("build_graph")), state)
    return render_script(graph, state["run_id"])
