#!/usr/bin/env python3
"""Regenerate salome_agent/verify/toplevel_api.json from a live introspect().

That fixture is the --no-session static-check API map (verify/static.py). It has
no authoritative source other than a real SALOME session, so it has to be
regenerated by hand whenever the SALOME build changes.

Usage:
    python3 scripts/regen-toplevel-api.py

Connects to the agent server named in ~/.salome_agent/server.json if one is
running (GUI plugin or headless); otherwise spawns a throwaway headless server
(needs $SALOME_ROOT or salome.root in config.json) and tears it down after.

A module whose live introspect comes back empty (e.g. pvsimple on a GUI server,
where it is loaded lazily) keeps its existing member list rather than being
wiped.
"""
import json
import os
import signal
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))

from salome_agent.executor_client import ExecutorClient  # noqa: E402

HS = Path(os.path.expanduser("~/.salome_agent/server.json"))
FIXTURE = REPO / "salome_agent" / "verify" / "toplevel_api.json"
MODULES = ["geompy", "smesh", "pvsimple"]


def _salome_root() -> str:
    root = os.environ.get("SALOME_ROOT")
    if root:
        return root
    cfg = REPO / "config.json"
    if cfg.exists():
        root = json.loads(cfg.read_text()).get("salome", {}).get("root")
        if root:
            return root
    sys.exit("set $SALOME_ROOT or salome.root in config.json")


def _spawn_server() -> subprocess.Popen:
    if HS.exists():
        HS.unlink()
    env = os.environ.copy()
    env["PATH"] = os.pathsep.join(
        p for p in env.get("PATH", "").split(os.pathsep) if ".venv" not in p)
    env.pop("VIRTUAL_ENV", None)
    proc = subprocess.Popen(
        [f"{_salome_root()}/salome", "shell", "--", "python3", "-m", "agent_server",
         "--serve-forever"],
        cwd=str(REPO), env=env, start_new_session=True)
    for _ in range(300):
        if HS.exists():
            return proc
        time.sleep(0.2)
    os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
    sys.exit("agent_server never wrote its handshake")


def _kill(proc: subprocess.Popen) -> None:
    try:
        os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
    except (ProcessLookupError, PermissionError):
        pass
    if HS.exists():
        HS.unlink()


def main() -> None:
    proc = None if HS.exists() else _spawn_server()
    try:
        hs = json.loads(HS.read_text())
        client = ExecutorClient(hs["host"], hs["port"], hs["token"], "regen-toplevel-api")
        raw = client.introspect(MODULES)
    finally:
        if proc is not None:
            _kill(proc)

    fixture = json.loads(FIXTURE.read_text()) if FIXTURE.exists() else {}
    for name in MODULES:
        members = sorted(m for m in raw.get(name, {}).get("members", [])
                         if not m.startswith("_"))
        if members:
            fixture[name] = {"members": members}
            print(f"{name}: {len(members)} members")
        else:
            print(f"{name}: live introspect empty — keeping existing "
                  f"({len(fixture.get(name, {}).get('members', []))} members)")

    FIXTURE.write_text(json.dumps(fixture, indent=2, sort_keys=True) + "\n")
    print(f"wrote {FIXTURE.relative_to(REPO)}")


if __name__ == "__main__":
    main()
